returns trigger
language plpgsql
security definer
set search_path to ''
as $function$
begin

  insert into public.users (
    id,
    nome,
    email
  )
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'nome', ''),
    coalesce(new.email, '')
  );

  return new;

end;
$function$;

