create table public.users (
  id uuid not null,
  created_at timestamptz not null default now(),
  nome text not null,
  email text not null,
  telefone text,
  foto text,
  ativo boolean not null default true,
  constraint users_pkey primary key (id),
  constraint users_auth_fkey foreign key (id) references auth.users (id) on delete cascade
);

create table public.empresas (
  id bigint generated by default as identity,
  created_at timestamptz not null default now(),
  razao_social text not null,
  nome_fantasia text,
  cnpj text not null,
  email text,
  telefone text,
  endereco text,
  numero text,
  complemento text,
  bairro text,
  cidade text,
  estado text,
  cep text,
  logo text,
  ativo boolean not null default true,
  constraint empresas_pkey primary key (id),
  constraint empresas_cnpj_unique unique (cnpj)
);

create table public.empresa_usuarios (
  id bigint generated by default as identity,
  created_at timestamptz not null default now(),
  id_empresa bigint not null,
  id_usuario uuid not null,
  tipo_acesso text not null default 'tecnico',
  aprovado boolean not null default false,
  ativo boolean not null default true,
  data_aprovacao timestamptz,
  aprovado_por uuid,
  constraint empresa_usuarios_pkey primary key (id),
  constraint empresa_usuarios_unique unique (id_empresa, id_usuario),
  constraint empresa_usuarios_empresa_fkey foreign key (id_empresa) references public.empresas (id) on delete cascade,
  constraint empresa_usuarios_usuario_fkey foreign key (id_usuario) references public.users (id) on delete cascade,
  constraint empresa_usuarios_aprovado_por_fkey foreign key (aprovado_por) references public.users (id) on delete set null,
  constraint empresa_usuarios_tipo_acesso_check check (tipo_acesso = any (array['administrador', 'supervisor', 'executor']))
);

create index idx_empresa_usuarios_usuario on public.empresa_usuarios using btree (id_usuario);
create index idx_empresa_usuarios_aprovado on public.empresa_usuarios using btree (id_empresa, aprovado);

